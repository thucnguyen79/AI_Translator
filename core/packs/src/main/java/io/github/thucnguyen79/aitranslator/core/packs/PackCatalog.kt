package io.github.thucnguyen79.aitranslator.core.packs

import io.github.thucnguyen79.aitranslator.core.model.Lang
import org.json.JSONObject

/** One downloadable file; [path] is relative to the pack folder (a folder when [extract] is set). */
data class PackFile(val url: String, val size: Long, val sha256: String, val path: String, val extract: String?)

enum class PackKind { LANGUAGE, SHARED, OPTIONAL }

data class Pack(
    val id: String,
    val kind: PackKind,
    val langs: List<Lang>,
    val requires: List<String>,
    val license: String,
    val files: List<PackFile>,
) {
    val size: Long get() = files.sumOf { it.size }
}

/** The catalog generated by tools/gen_packs.py (assets/packs.json). */
class PackCatalog(val version: Int, val packs: List<Pack>) {
    private val byId = packs.associateBy { it.id }

    operator fun get(id: String): Pack = byId[id] ?: error("Unknown pack $id")

    fun languagePack(lang: Lang): Pack = packs.first { it.kind == PackKind.LANGUAGE && lang in it.langs }

    /** [id] and everything it requires, dependencies first. */
    fun withRequirements(id: String): List<Pack> {
        val out = LinkedHashSet<Pack>()
        fun visit(p: Pack) {
            p.requires.forEach { visit(get(it)) }
            out += p
        }
        visit(get(id))
        return out.toList()
    }

    companion object {
        fun parse(json: String): PackCatalog {
            val root = JSONObject(json)
            val packs = root.getJSONArray("packs").let { arr ->
                (0 until arr.length()).map { i ->
                    val p = arr.getJSONObject(i)
                    Pack(
                        id = p.getString("id"),
                        kind = PackKind.valueOf(p.getString("kind").uppercase()),
                        langs = p.getJSONArray("langs").strings().map(Lang::of),
                        requires = p.getJSONArray("requires").strings(),
                        license = p.optString("license"),
                        files = p.getJSONArray("files").let { files ->
                            (0 until files.length()).map { j ->
                                val f = files.getJSONObject(j)
                                PackFile(
                                    url = f.getString("url"),
                                    size = f.getLong("size"),
                                    sha256 = f.getString("sha256"),
                                    path = f.getString("path"),
                                    extract = f.optString("extract").ifEmpty { null },
                                )
                            }
                        },
                    )
                }
            }
            return PackCatalog(root.getInt("version"), packs)
        }

        private fun org.json.JSONArray.strings() = (0 until length()).map { getString(it) }
    }
}
